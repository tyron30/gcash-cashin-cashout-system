-- ---------------------------------------------------------------------
-- profiles: one row per login (auth.users). Holds the role.
-- is_active defaults to FALSE so a stranger who somehow signs up can do
-- nothing until the owner activates the account.
-- ---------------------------------------------------------------------
create table public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  full_name   text not null,
  role        text not null default 'staff',
  is_active   boolean not null default false,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint profiles_full_name_check check (char_length(btrim(full_name)) between 1 and 80),
  constraint profiles_role_check check (role in ('admin', 'staff'))
);

-- ---------------------------------------------------------------------
-- store_settings: exactly ONE row (the id can only ever be TRUE).
-- ---------------------------------------------------------------------
create table public.store_settings (
  id                  boolean primary key default true,
  store_name          text not null default 'My Store',
  timezone            text not null default 'Asia/Manila',
  -- 0 = staff see today only. 1 = today and yesterday. And so on.
  staff_history_days  integer not null default 0,
  updated_by          uuid references public.profiles (id),
  updated_at          timestamptz not null default now(),
  constraint store_settings_singleton check (id),
  constraint store_settings_name_check check (char_length(btrim(store_name)) between 1 and 80),
  constraint store_settings_history_check check (staff_history_days between 0 and 31)
);

insert into public.store_settings (id) values (true) on conflict do nothing;

-- ---------------------------------------------------------------------
-- transactions: every cash-in / cash-out. Rows are never deleted.
-- ---------------------------------------------------------------------
create table public.transactions (
  id                     uuid primary key default gen_random_uuid(),

  -- Stored as TEXT so leading zeros are never lost.
  reference_number       text not null,
  -- Same reference without spaces, upper case. Used for searching and
  -- for the duplicate warning. Generated by the database, cannot be faked.
  reference_key          text generated always as (upper(regexp_replace(reference_number, '\s+', '', 'g'))) stored,

  transaction_type       text not null,
  amount                 numeric(12, 2) not null,
  sender_receiver_name   text,
  notes                  text,

  transaction_timestamp  timestamptz not null default now(),
  -- The store's local date (Asia/Manila). Filled in by a trigger from
  -- transaction_timestamp, so the app can never get it wrong.
  business_date          date not null,

  status                 text not null default 'completed',
  void_reason            text,
  voided_at              timestamptz,
  voided_by              uuid references public.profiles (id),

  -- A random id the app creates once per form. Saving the same form twice
  -- can never create two records.
  client_request_id      uuid,

  created_by             uuid not null references public.profiles (id),
  updated_by             uuid references public.profiles (id),
  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now(),

  constraint transactions_type_check
    check (transaction_type in ('cash_in', 'cash_out')),
  constraint transactions_status_check
    check (status in ('completed', 'voided')),
  constraint transactions_amount_check
    check (amount > 0 and amount <= 999999.99),
  constraint transactions_reference_check
    check (reference_number = btrim(reference_number) and reference_key ~ '^[A-Z0-9]{8,20}$'),
  constraint transactions_name_check
    check (sender_receiver_name is null
           or (char_length(sender_receiver_name) between 1 and 60
               and sender_receiver_name !~ '[[:cntrl:]]')),
  constraint transactions_notes_check
    check (notes is null
           or (char_length(notes) between 1 and 200
               and notes !~ '[[:cntrl:]]')),
  constraint transactions_void_consistency_check
    check (
      (status = 'completed' and void_reason is null and voided_at is null and voided_by is null)
      or
      (status = 'voided' and char_length(btrim(void_reason)) >= 5
         and voided_at is not null and voided_by is not null)
    )
);

-- NOTE ON REFERENCE NUMBERS: reference_number is intentionally NOT unique.
-- The same reference may legitimately appear twice (different GCash
-- transaction types, or an honest re-entry after a void), so the app WARNS
-- about duplicates instead of rejecting them. If you later confirm that your
-- references are always unique, a unique index on reference_key is a
-- one-line change.

create unique index transactions_client_request_uidx
  on public.transactions (created_by, client_request_id)
  where client_request_id is not null;

create index transactions_business_date_idx   on public.transactions (business_date, status);
create index transactions_timestamp_idx       on public.transactions (transaction_timestamp desc);
create index transactions_type_idx            on public.transactions (transaction_type);
create index transactions_status_idx          on public.transactions (status);
create index transactions_created_by_idx      on public.transactions (created_by, business_date);
create index transactions_reference_key_idx   on public.transactions (reference_key);

-- ---------------------------------------------------------------------
-- daily_closings: one row per business date (single store).
-- ---------------------------------------------------------------------
create table public.daily_closings (
  id                      uuid primary key default gen_random_uuid(),
  business_date           date not null unique,
  status                  text not null default 'open',
  cash_counted            numeric(12, 2),
  recorded_cash_balance   numeric(12, 2),
  -- counted - recorded. Positive = overage, negative = shortage.
  shortage_overage        numeric(12, 2) generated always as (cash_counted - recorded_cash_balance) stored,
  closing_notes           text,
  closed_by               uuid references public.profiles (id),
  closed_at               timestamptz,
  reopened_by             uuid references public.profiles (id),
  reopened_at             timestamptz,
  reopen_reason           text,
  created_at              timestamptz not null default now(),
  updated_at              timestamptz not null default now(),
  constraint daily_closings_status_check check (status in ('open', 'closed')),
  constraint daily_closings_counted_check check (cash_counted is null or cash_counted >= 0),
  constraint daily_closings_recorded_check check (recorded_cash_balance is null or recorded_cash_balance >= 0),
  constraint daily_closings_notes_check check (closing_notes is null or char_length(closing_notes) <= 500),
  constraint daily_closings_closed_check check (status <> 'closed' or (closed_by is not null and closed_at is not null))
);

