-- ---------- Profiles: nobody can promote themselves ----------
-- Second lock behind the column permissions in migration 3. Role and access
-- can only change through admin_update_profile(), or from the Supabase
-- dashboard / SQL editor (where auth.uid() is null).

create or replace function public.guard_profile_changes()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if (new.role is distinct from old.role
      or new.is_active is distinct from old.is_active
      or new.id is distinct from old.id)
     and auth.uid() is not null
     and coalesce(current_setting('app.admin_profile_change', true), '') <> 'on'
  then
    raise exception 'Role and access can only be changed by the owner.' using errcode = '42501';
  end if;
  return new;
end;
$$;

create trigger profiles_10_guard
  before update on public.profiles
  for each row execute function public.guard_profile_changes();

-- ---------- Transactions: business rules inside the database ----------

-- 1) business_date always comes from the timestamp, in Manila time.
--    11:30 pm Manila belongs to THAT Manila day, not the next UTC day.
create or replace function public.set_business_date()
returns trigger
language plpgsql security definer
set search_path = ''
as $$
begin
  new.business_date := (new.transaction_timestamp at time zone public.store_timezone())::date;
  return new;
end;
$$;

create trigger transactions_10_set_business_date
  before insert or update of transaction_timestamp on public.transactions
  for each row execute function public.set_business_date();

-- 2) Protect fields that must never change, and freeze voided records.
create or replace function public.protect_transaction_fields()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if old.status = 'voided' then
    raise exception 'Voided transactions cannot be changed.' using errcode = '42501';
  end if;

  if new.id is distinct from old.id
     or new.created_by is distinct from old.created_by
     or new.created_at is distinct from old.created_at
     or new.transaction_type is distinct from old.transaction_type
     or new.client_request_id is distinct from old.client_request_id
  then
    raise exception 'Owner, type, original creation time, and request id of a transaction cannot be changed.'
      using errcode = '42501';
  end if;

  return new;
end;
$$;

create trigger transactions_20_protect_fields
  before update on public.transactions
  for each row execute function public.protect_transaction_fields();

-- 3) A closed business date is locked until the owner reopens it.
create or replace function public.enforce_open_business_day()
returns trigger
language plpgsql security definer
set search_path = ''
as $$
begin
  if exists (select 1 from public.daily_closings c
             where c.business_date = new.business_date and c.status = 'closed') then
    raise exception 'Business date % is closed. Reopen the day before changing its transactions.', new.business_date;
  end if;

  if tg_op = 'UPDATE' and old.business_date <> new.business_date then
    if exists (select 1 from public.daily_closings c
               where c.business_date = old.business_date and c.status = 'closed') then
      raise exception 'Business date % is closed. Reopen the day before changing its transactions.', old.business_date;
    end if;
  end if;

  return new;
end;
$$;

create trigger transactions_30_enforce_open_day
  before insert or update on public.transactions
  for each row execute function public.enforce_open_business_day();

-- ===================== 20261014000300_rls_policies.sql =====================
-- =====================================================================
-- GCash Monitor - Migration 3 of 5: Row Level Security policies
-- RLS decides WHICH ROWS a logged-in user can read. Writes to money
-- tables are not allowed directly at all: they go through the approved
-- functions in migration 4.
-- "(select ...)" wrappers make Postgres evaluate each check once per
-- query instead of once per row (faster).
-- =====================================================================

-- ---------- profiles ----------
-- Everyone active can see names (needed to show "recorded by").
-- A person can always read their own profile, even if inactive, so the
-- app can tell them "your account is not active yet".
create policy profiles_select
  on public.profiles for select to authenticated
  using (id = (select auth.uid()) or (select public.is_active_user()));

-- People may edit only their own full_name (column permission below).
-- Role and is_active are protected by column permissions AND a trigger.
create policy profiles_update_own_name
  on public.profiles for update to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

-- ---------- store_settings ----------
create policy store_settings_select
  on public.store_settings for select to authenticated
  using ((select public.is_active_user()));

-- ---------- transactions ----------
-- Owner: every transaction.
-- Staff: only recent days (default = today only, set in store_settings).
create policy transactions_select
  on public.transactions for select to authenticated
  using (
    (select public.is_admin())
    or (
      (select public.is_active_user())
      and business_date >= (select public.current_business_date()) - (select public.staff_history_days())
    )
  );

-- ---------- daily_closings and audit_logs: owner only ----------
create policy daily_closings_select
  on public.daily_closings for select to authenticated
  using ((select public.is_admin()));

create policy audit_logs_select
  on public.audit_logs for select to authenticated
  using ((select public.is_admin()));

-- No INSERT / UPDATE / DELETE policies exist on purpose for transactions,
-- daily_closings, audit_logs, and store_settings. With RLS on, that means
-- "denied", even if a permission were granted by mistake later.

-- ---------- Table permissions (second layer) ----------
-- Supabase gives anon/authenticated broad permissions on new tables by
-- default. Take everything away, then give back only what is needed.
revoke all on public.profiles       from anon, authenticated;
revoke all on public.store_settings from anon, authenticated;
revoke all on public.transactions   from anon, authenticated;
revoke all on public.daily_closings from anon, authenticated;
revoke all on public.audit_logs     from anon, authenticated;

grant select on public.profiles       to authenticated;
grant select on public.store_settings to authenticated;
grant select on public.transactions   to authenticated;
grant select on public.daily_closings to authenticated;
grant select on public.audit_logs     to authenticated;

-- Only the name column of profiles can be edited directly.
grant update (full_name) on public.profiles to authenticated;

-- Any table created in future starts with no access for anon/authenticated.
alter default privileges in schema public revoke all on tables from anon, authenticated;

-- ===================== 20261014000400_rpc_functions.sql =====================
-- =====================================================================
-- GCash Monitor - Migration 4 of 5: approved database functions (RPC)
-- The app calls these instead of writing to tables. Each one:
--   * checks who is calling (auth.uid()) and their role,
--   * validates the data again (never trust the browser),
--   * writes the audit log in the same transaction.
-- "security definer" = runs with the owner's rights, so it can write to
-- tables that users cannot write to directly.
-- =====================================================================

-- ---------- Shared validation (internal) ----------
create or replace function public.validate_transaction_fields(
  p_reference text,
  p_amount numeric,
  p_name text,
  p_notes text
)
returns void
language plpgsql
set search_path = ''
as $$
begin
  if upper(regexp_replace(coalesce(p_reference, ''), '\s+', '', 'g')) !~ '^[A-Z0-9]{8,20}$' then
    raise exception 'Enter a valid reference number (8 to 20 letters or numbers).';
  end if;

  if p_amount is null or p_amount <= 0 then
    raise exception 'Amount must be greater than zero.';
  end if;
  if p_amount > 999999.99 then
    raise exception 'Amount is too large. The maximum is 999,999.99.';
  end if;
  if round(p_amount, 2) <> p_amount then
    raise exception 'Amount can have at most 2 decimal places.';
  end if;

  if p_name is not null and (char_length(p_name) > 60 or p_name ~ '[[:cntrl:]]') then
    raise exception 'The name must be 60 characters or fewer.';
  end if;
  if p_notes is not null and (char_length(p_notes) > 200 or p_notes ~ '[[:cntrl:]]') then
    raise exception 'Notes must be 200 characters or fewer.';
  end if;
end;
$$;

-- ---------- create_transaction ----------
create or replace function public.create_transaction(
  p_transaction_type text,
  p_reference_number text,
  p_amount numeric,
  p_sender_receiver_name text default null,
  p_notes text default null,
  p_transaction_timestamp timestamptz default null,
  p_client_request_id uuid default null
)
returns public.transactions
language plpgsql security definer
set search_path = ''
as $$
declare
  v_uid   uuid := auth.uid();
  v_row   public.transactions;
  v_ref   text := public.normalize_reference(p_reference_number);
  v_name  text := nullif(btrim(regexp_replace(coalesce(p_sender_receiver_name, ''), '\s+', ' ', 'g')), '');
  v_notes text := nullif(btrim(coalesce(p_notes, '')), '');
  v_ts    timestamptz;
begin
  if v_uid is null or not public.is_active_user() then
    raise exception 'You are not allowed to record transactions.' using errcode = '42501';
  end if;

  -- Same form submitted twice -> return the record that already exists.
  if p_client_request_id is not null then
    select * into v_row from public.transactions t
    where t.created_by = v_uid and t.client_request_id = p_client_request_id;
    if found then
      return v_row;
    end if;
  end if;

  if p_transaction_type is null or p_transaction_type not in ('cash_in', 'cash_out') then
    raise exception 'Choose Cash In or Cash Out.';
  end if;

  perform public.validate_transaction_fields(v_ref, p_amount, v_name, v_notes);

  -- Staff always get the server time. Only the owner may set another time.
  v_ts := coalesce(p_transaction_timestamp, now());
  if v_ts > now() + interval '2 minutes' then
    raise exception 'Date and time cannot be in the future.';
  end if;
  if p_transaction_timestamp is not null
     and abs(extract(epoch from (v_ts - now()))) > 120
     and not public.is_admin() then
    raise exception 'Only the owner can change the transaction date or time.' using errcode = '42501';
  end if;

  begin
    insert into public.transactions
      (reference_number, transaction_type, amount, sender_receiver_name, notes,
       transaction_timestamp, created_by, client_request_id)
    values
      (v_ref, p_transaction_type, p_amount, v_name, v_notes,
       v_ts, v_uid, p_client_request_id)
    returning * into v_row;
  exception when unique_violation then
    -- Two identical requests arrived at the same moment. Keep the first.
    select * into v_row from public.transactions t
    where t.created_by = v_uid and t.client_request_id = p_client_request_id;
    if found then
      return v_row;
    end if;
    raise;
  end;

  perform public.write_audit_log('transaction.created', 'transaction', v_row.id, null, null,
    jsonb_build_object(
      'reference_number', v_row.reference_number,
      'transaction_type', v_row.transaction_type,
      'amount', v_row.amount,
      'business_date', v_row.business_date));

  return v_row;
end;
$$;

-- ---------- update_transaction (owner only) ----------
create or replace function public.update_transaction(
  p_id uuid,
  p_reference_number text,
  p_amount numeric,
  p_sender_receiver_name text,
  p_notes text,
  p_transaction_timestamp timestamptz,
  p_reason text
)
returns public.transactions
language plpgsql security definer
set search_path = ''
as $$
declare
  v_old    public.transactions;
  v_new    public.transactions;
  v_reason text := btrim(coalesce(p_reason, ''));
  v_ref    text := public.normalize_reference(p_reference_number);
  v_name   text := nullif(btrim(regexp_replace(coalesce(p_sender_receiver_name, ''), '\s+', ' ', 'g')), '');
  v_notes  text := nullif(btrim(coalesce(p_notes, '')), '');
  v_ts     timestamptz := p_transaction_timestamp;
begin
  perform public.assert_admin();

  if char_length(v_reason) < 5 then
    raise exception 'Enter a reason (at least 5 characters).';
  end if;
  if v_ts is null then
    raise exception 'Date and time are required.';
  end if;
  if v_ts > now() + interval '2 minutes' then
    raise exception 'Date and time cannot be in the future.';
  end if;

  select * into v_old from public.transactions t where t.id = p_id for update;
  if not found then
    raise exception 'Transaction not found.';
  end if;
  if v_old.status = 'voided' then
    raise exception 'Voided transactions cannot be edited.';
  end if;

  perform public.validate_transaction_fields(v_ref, p_amount, v_name, v_notes);

  if (v_old.reference_number, v_old.amount, v_old.sender_receiver_name, v_old.notes, v_old.transaction_timestamp)
     is not distinct from (v_ref, p_amount, v_name, v_notes, v_ts) then
    raise exception 'Nothing was changed.';
  end if;

  update public.transactions t
     set reference_number = v_ref,
         amount = p_amount,
         sender_receiver_name = v_name,
         notes = v_notes,
         transaction_timestamp = v_ts,
         updated_by = auth.uid()
   where t.id = p_id
  returning * into v_new;

  perform public.write_audit_log('transaction.updated', 'transaction', p_id, v_reason,
    jsonb_build_object(
      'reference_number', v_old.reference_number, 'amount', v_old.amount,
      'sender_receiver_name', v_old.sender_receiver_name, 'notes', v_old.notes,
      'transaction_timestamp', v_old.transaction_timestamp, 'business_date', v_old.business_date),
    jsonb_build_object(
      'reference_number', v_new.reference_number, 'amount', v_new.amount,
      'sender_receiver_name', v_new.sender_receiver_name, 'notes', v_new.notes,
      'transaction_timestamp', v_new.transaction_timestamp, 'business_date', v_new.business_date));

  return v_new;
end;
$$;

